#!/usr/bin/env python3
"""Regenerates docs/testing/KNOWN-BUGS.md from the tests tagged #[Group('known-bug')].

    python3 tests/bin/known-bugs.py

Each entry shows the test and the text of its `// KNOWN BUG: ...` comment.
"""
import collections
import glob
import os
import re

os.chdir(os.path.join(os.path.dirname(__file__), '..', '..'))
rows = []
for f in sorted(glob.glob('tests/**/*.php', recursive=True)):
    s = open(f).read()
    area = os.path.dirname(f)[6:] or 'tests'
    m = re.search(r"#\[Group\('known-bug'\)\]\s*(?:final |abstract )?class (\w+)", s)
    if m:
        c = re.search(r'KNOWN BUG[^\n]*', s)
        rows.append((area, os.path.basename(f), m.group(1) + ' (whole class)', c.group(0).replace('// ', '').strip() if c else ''))
    pattern = r"#\[Group\('known-bug'\)\](?:\s*#\[[^\]]*\])*\s*public function (\w+)\([^)]*\)[^{]*\{(.*?)(?=\n    (?:#\[|public function|private function|protected function|/\*\*)|\n\}\s*$)"
    for mm in re.finditer(pattern, s, re.S):
        c = re.search(r'//\s*KNOWN BUG[^\n]*(?:\n\s*//[^\n]*)*', mm.group(2))
        text = ''
        if c:
            text = ' '.join(x.strip().lstrip('/').strip() for x in c.group(0).split('\n'))
            text = re.sub(r'^KNOWN BUG( \(([^)]*)\))?:?\s*', '', text)
        rows.append((area, os.path.basename(f), mm.group(1), text))

by = collections.defaultdict(list)
for area, f, n, t in rows:
    by[area].append((f, n, t))

out = [
    '# Known bugs pinned by the tests', '',
    "Every entry is a test tagged `#[Group('known-bug')]`: it passes against the **current** behaviour and records something that looks wrong. During the CI4 port decide for each one whether to keep the behaviour (a faithful port) or fix it on purpose, and then update that single test. `vendor/bin/phpunit --exclude-group known-bug` runs everything that must stay identical.", '',
    f'Generated by `python3 tests/bin/known-bugs.py` from the test sources ({len(rows)} entries). The wording is the `KNOWN BUG:` comment in the test; open the test for the exact scenario.', '',
]
for area in sorted(by):
    out += ['## ' + area, '', '| Test | Problem |', '|---|---|']
    for f, n, t in sorted(by[area]):
        out.append(f'| `{f}` :: `{n}` | {t.replace("|", "/") or "(see the test)"} |')
    out.append('')
open('docs/testing/KNOWN-BUGS.md', 'w').write('\n'.join(out))
print(len(rows), 'entries')
