#!/usr/bin/env bash
# Regenerates tests/Fixtures/schema.sql from an up-to-date database (structure only, no data).
#
# Run it after adding a migration, on a database that is already migrated:
#   tests/bin/dump-schema.sh                      # podman: container alies-db, database alies
#   DUMP_CMD="mariadb-dump -h host -u u -pp" DUMP_DB=mydb tests/bin/dump-schema.sh
#
# The migrations table is part of the dump, its version row is added by seed.sql.
set -euo pipefail
cd "$(dirname "$0")/../.."

DUMP_DB="${DUMP_DB:-alies}"
DUMP_CMD="${DUMP_CMD:-podman exec ${DB_CONTAINER:-alies-db} mariadb-dump -uroot -p${DB_ROOT_PASS:-root}}"
OUT=tests/Fixtures/schema.sql

{
    echo "-- Structure of the Alies database, generated by tests/bin/dump-schema.sh."
    echo "-- Do not edit by hand."
    echo "SET FOREIGN_KEY_CHECKS=0;"
    $DUMP_CMD --no-data --skip-comments --skip-add-drop-table --skip-triggers "$DUMP_DB" \
        | sed -E 's/ AUTO_INCREMENT=[0-9]+//' \
        | grep -v -E '^(/\*|SET |LOCK |UNLOCK )' \
        | grep -v '^$'
    echo "SET FOREIGN_KEY_CHECKS=1;"
} > "$OUT"

echo "wrote $OUT ($(grep -c '^CREATE TABLE' "$OUT") tables)"
